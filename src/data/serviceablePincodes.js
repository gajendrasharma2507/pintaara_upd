export const SERVICEABLE_PINCODE_SET = new Set(SERVICEABLE_PINCODES);

export const UNSERVICEABLE_PINCODE_MESSAGE =
    'Delivery is not available for this pincode. We currently deliver only to serviceable areas.';

/**
 * Checks whether a pincode is in the serviceable delivery list.
 */
export function isServiceablePincode(pin) {
    const clean = String(pin || '').trim();
    return clean.length === 6 && SERVICEABLE_PINCODE_SET.has(clean);
}

/**
 * Returns prefix-matching serviceable pincode suggestions for autocomplete.
 */
export function getPincodeSuggestions(query, limit = 8) {
    const q = String(query || '').trim();
    if (!q) return [];
    const results = [];
    for (let i = 0; i < SERVICEABLE_PINCODES.length; i++) {
        if (SERVICEABLE_PINCODES[i].startsWith(q)) {
            results.push(SERVICEABLE_PINCODES[i]);
            if (results.length >= limit) break;
        }
    }
    return results;
}
