export function getBlueprintById(id) {
  if (!id) return blueprintSheets[0];
  const found = blueprintSheets.find(b => b.id.toLowerCase() === id.toLowerCase() || b.code.toLowerCase() === id.toLowerCase());
  return found || blueprintSheets[0];
}
